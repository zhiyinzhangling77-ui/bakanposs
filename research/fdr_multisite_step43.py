"""旗43（穴⑤の残り）：ブートCI"何サイト有意"型の主張に族補正をかける。

問題：本研究の多サイト主張の多くは「per-siteブートCIが0を跨がないサイトを数える」型
（例 旗42 森林25/37でQ10↑, 旗31 乾燥3/3でθ→GER）。だが(a)サイト数だけ検定を回して族補正なし
＝偶然有意の水増し、(b)ブートCIは自己相関で狭すぎ＝per-siteαが名目0.025より大きいかも、
(c)サイトは地理的に非独立(擬似反復)＝有効試行数<サイト数。この3点に同時に耐えるかを見る。

方法：族ごとに、帰無(どのサイトも真の効果ゼロ)下で「片方向にCI有意」になる数 ~ Binomial(M,α)。
観測 k がこの上側裾を超えるか（二項上側p）を、
  ・α掃引 {0.025(名目95%CI片側), 0.05, 0.10, 0.20} …自己相関でCIが狭い懸念に耐えるか
  ・M をクラスタ数に縮めて再判定 …擬似反復(非独立)に耐えるか
で見る。α=0.20でも生存＝岩盤／名目αのみ生存＝脆い／クラスタ縮約で崩れる＝擬似反復依存。

数値は全て FLAGS_LOG/VALIDITY_SYNTHESIS 記録済みの実データ出力（本ファイルは補正計算のみ・捏造なし）。

    python research/fdr_multisite_step43.py
"""
from __future__ import annotations
from math import comb

# (名前, k=片方向CI有意サイト数, M=検定サイト数, 方向, n_clusters(地理独立数,概算), 出典)
FAMILIES = [
    ("旗42 水分依存Q10↑ 森林(チャンバー直接)", 25, 37, "正", 22,
     "北米/欧州/アジア/熱帯に散在, おおよそ独立地点22"),
    ("旗42 水分依存Q10↑ 草原(チャンバー直接)", 4, 5, "正", 5, "分散した草原5"),
    ("旗26 水分依存Q10↑ 森林(フラックス)", 5, 8, "正", 6, "日本森林多数=クラスタ気味, 概6"),
    ("旗40 ~4日メモリ 森林(チャンバー直接,厳基準)", 12, 35, "正", 20,
     "欧/北米/アジアに散在, 概20独立"),
    ("旗31 θ→GER 乾燥ステップ(年ブロックブート生存)", 3, 3, "正", 1,
     "MN-Hst/Nkh/Kbu=モンゴル近接3=1クラスタ"),
    ("旗36 θ→γLE 乾燥ステップ(水制限ET)", 3, 3, "正", 1, "同上1クラスタ"),
    ("旗36 Bowen反転 乾燥ステップ(θ→γLE>0 & θ→γH<0同時)", 3, 3, "正", 1, "同上1クラスタ"),
    ("旗14 呼吸の相乗支配 (O-info z<0)", 19, 21, "負(相乗)", 12,
     "21サイト=日本森林に偏るがアジア/高山/亜寒帯/熱帯も, 概12独立"),
]

ALPHAS = [0.025, 0.05, 0.10, 0.20]


def binom_upper(k, M, a):
    """P(X>=k), X~Binomial(M,a)。観測がこの帰無上側裾より小さいほど有意。"""
    return sum(comb(M, i) * a**i * (1 - a)**(M - i) for i in range(k, M + 1))


def verdict_row(k, M):
    ps = [binom_upper(k, M, a) for a in ALPHAS]
    # 生存=補正後 p<0.05。α=0.20でも生存なら岩盤、名目のみなら脆い
    surv = [p < 0.05 for p in ps]
    if all(surv):
        v = "◎岩盤(α=0.20でも偶然超え)"
    elif surv[0] and not surv[-1]:
        # どこまで生存するか
        last = max(i for i, s in enumerate(surv) if s)
        v = f"○α≤{ALPHAS[last]:.2f}まで生存(自己相関に中耐性)"
    elif not surv[0]:
        v = "×名目でも偶然を超えない"
    else:
        v = "○条件付き生存"
    return ps, v


def main():
    print("=== 旗43：ブートCI『何サイト有意』型の族補正（二項上側p, α掃引 × クラスタ縮約）===")
    print("  帰無=全サイト真の効果ゼロ。観測kが Binomial(M,α) の上側裾を超えるか。p<0.05で補正後も生存。\n")
    head = f"  {'族':<40} {'k/M':>7} " + " ".join(f"p@α={a:.3f}".rjust(11) for a in ALPHAS) + "   判定"
    print(head)
    for name, k, M, direc, ncl, note in FAMILIES:
        ps, v = verdict_row(k, M)
        pstr = " ".join((f"{p:.1e}" if p < 1e-3 else f"{p:.3f}").rjust(11) for p in ps)
        print(f"  {name:<40} {f'{k}/{M}':>7} {pstr}   {v}")

    print("\n  === クラスタ縮約（擬似反復：M→独立地点数, k は最大でクラスタ数に制限）===")
    print("  近接サイトを1試行に潰し、それでも偶然を超えるか。超えなければ主張は擬似反復依存。\n")
    print(f"  {'族':<40} {'k*/M*':>8} {'p@α=0.05':>11} {'p@α=0.20':>11}   判定")
    for name, k, M, direc, ncl, note in FAMILIES:
        kc = min(k, ncl)                    # クラスタ数を超える有意は数えない(保守)
        p05 = binom_upper(kc, ncl, 0.05); p20 = binom_upper(kc, ncl, 0.20)
        if ncl <= 1:
            v = "―(1クラスタ=反復n1, 二項検定不能=擬似反復の穴そのもの)"
        elif p20 < 0.05:
            v = "◎縮約でも岩盤"
        elif p05 < 0.05:
            v = "○縮約で中耐性"
        else:
            v = "×縮約で偶然に埋もれる=擬似反復依存"
        print(f"  {name:<40} {f'{kc}/{ncl}':>8} {p05:>11.1e} {p20:>11.1e}   {v}")

    print("\n  === 読み方 ===")
    print("  ・◎岩盤：CIが自己相関で狭すぎ(α=0.20)ても偶然を超える＝族補正で消えない本物。")
    print("  ・×名目でも超えない／×縮約で埋もれる：族補正・擬似反復で格下げすべき主張。")
    print("  ・1クラスタ(乾燥ステップθ族)＝二項検定は成り立たない＝これは穴①擬似反復そのもの。")
    print("    効果量+CIは実在だが『何サイト有意』の統計的重みは反復n=1＝一般化不可, スコープをこの母集団に限定(既対応)。")


if __name__ == "__main__":
    main()
